// Claude Code customization is independent of the sample's inference integrations.

import { execFile, spawn } from 'node:child_process';
import { promisify } from 'node:util';
import fs from 'node:fs/promises';
import path from 'node:path';
import type { AgentConfig } from './types.js';
import type { Template } from './templates/registry.js';
import { PROVIDERS } from './providers.js';

const execFileAsync = promisify(execFile);

export interface AssistantDetection {
  id: string;
  available: boolean;
  version?: string;
  installHint: string;
}

/** Detect whether the Claude Code CLI is installed and on PATH. */
export async function detectClaudeCode(): Promise<AssistantDetection> {
  const installHint =
    'Install Claude Code: npm install -g @anthropic-ai/claude-code  (then run `claude` in the project).';
  try {
    const { stdout } = await execFileAsync('claude', ['--version'], { timeout: 5000 });
    return { id: 'claude-code', available: true, version: stdout.trim(), installHint };
  } catch {
    return { id: 'claude-code', available: false, installHint };
  }
}

/** Build the project-specific CLAUDE.md so the assistant starts with the architecture in context. */
export function generateClaudeMd(config: AgentConfig, template: Template): string {
  const integrations = template.aiFeatures.map((f) => f.name + ': ' + PROVIDERS[f.provider].label + ' (key ' + f.keyEnv + ', model ' + f.modelEnv + ')').join('; ');
  const surfaces = template.supportedSurfaces.join(', ');
  const scopes = template.requiredScopes.length ? template.requiredScopes.join(', ') : '(none declared)';
  const caps = template.requiredCapabilities.join(', ');
  const start = template.startCommands.join(' && ');
  const setup = template.setupCommands.join(' && ');

  return `# CLAUDE.md — ${config.info.appName}

Guidance for Claude Code (and other AI coding assistants) working in this project. This project was
scaffolded by \`create-zoom-agent\` from the **${template.name}** template.

## Project purpose
${config.info.description}

An AI-powered agent for Zoom Workplace, surfaced in: ${surfaces}.

## Architecture overview
- **Template:** ${template.name} (${template.id})
- **Provider integration:** ${providerIntegrationNote(template.providerIntegration)}
- **AI integrations:** ${integrations}
- **Zoom app type:** General App (user OAuth)
${template.sourceRepo ? `- **Upstream reference:** ${template.sourceRepo}${template.sourceRef ? ` @ ${template.sourceRef}` : ''}` : ''}

## Zoom integrations
- **Capabilities:** ${caps}
- **OAuth scopes:** ${scopes}
${template.manifestPath ? `- **Manifest:** \`${template.manifestPath}\` is the authoritative, capability-complete app manifest for this sample.` : '- **Manifest:** \`zoom-manifest.json\` was generated by the CLI for Marketplace creation.'}

## Local development
\`\`\`bash
${setup}
# review .env (already created from your answers)
${start}
\`\`\`

## Authentication requirements
- Zoom credentials live in \`.env\` (git-ignored). Never commit them or print them.
- The app's AI calls use \`${template.aiFeatures.map((f) => f.keyEnv).join(", ")}\`.
- Uses user-level OAuth (authorization code grant).

## Existing working functionality to PRESERVE
This project is a working starting point, not a shell. Before changing anything:
1. Read the source and the README to map what already works.
2. Preserve the existing Zoom integration (OAuth, webhook verification, message/event handling).
3. Reuse existing components; make the **minimal** change needed.
${template.supportedSurfaces.includes('rtms') || template.id === 'hitl-workplace-agent' ? '4. Preserve the **Observe → Recommend → Approve → Execute** pattern — AI must never mutate user or Workplace state without explicit human approval.' : '4. If you add actions that mutate Zoom/Workplace state, gate them behind explicit user approval (Observe → Recommend → Approve → Execute).'}

## Testing instructions
- Run any tests the project ships (\`npm test\` where present).
- Mock Zoom and AI calls in tests; never use live credentials in automated tests.
- After changes, re-run the app locally and exercise the affected surface.

## Development constraints
- Do not expose or log secrets.
- Do not auto-execute destructive or outward-facing actions without confirmation.
- Report what changed and what remains unverified.
`;
}

/** Build a short development brief describing the template and suggested next tasks. */
export function generateDevBrief(config: AgentConfig, template: Template): string {
  const integrations = template.aiFeatures.map((f) => f.name + ': ' + PROVIDERS[f.provider].label + ' (key ' + f.keyEnv + ', model ' + f.modelEnv + ')').join('; ');
  const extendIdeas = suggestedTasks(template);
  return `# Development Brief — ${config.info.appName}

A quick orientation for your first Claude Code session.

## What you're starting from
- **Reference template:** ${template.name} (${template.id})
- **Zoom app type:** General App (OAuth)
- **AI integrations:** ${integrations}
- **Configured capabilities:** ${template.requiredCapabilities.join(', ')}
- **Surfaces:** ${template.supportedSurfaces.join(', ')}

## Features you can extend
${extendIdeas.map((t) => `- ${t}`).join('\n')}

## Suggested first customization tasks
1. Read the README and \`CLAUDE.md\`, then summarize the current architecture back to me.
2. Create a branch for your change.
3. Describe the change you want; implement the minimal version; run the tests; report what changed.

## Ground rules
- Preserve existing Zoom integrations and the human-in-the-loop approval pattern.
- Keep provider-specific code separate from Zoom integration code.
- Never commit \`.env\` or print secrets.
`;
}

function providerIntegrationNote(mode: Template['providerIntegration']): string {
  if (mode === 'sample-native') return 'this app ships its own AI client';
  if (mode === 'fetch') return 'provider-agnostic adapter (reads AI_PROVIDER at runtime)';
  return 'no built-in AI yet — wire in your selected provider during customization';
}

function suggestedTasks(template: Template): string[] {
  const base: string[] =
    template.providerIntegration === 'none'
      ? ['Wire in your AI provider and add a first AI call (e.g. summarize meeting content or a chat message).']
      : ['Tune the AI system prompt for your use case.', 'Add a new command or intent the agent responds to.'];
  if (template.supportedSurfaces.includes('team_chat')) {
    base.push('Add an interactive approval card before the bot takes an action.');
  }
  if (template.supportedSurfaces.includes('rtms') || template.id === 'hitl-workplace-agent') {
    base.push('Extract a new kind of follow-up (decision, risk, action item) from meeting transcripts.');
  }
  return base;
}

/** Write CLAUDE.md and DEVELOPMENT_BRIEF.md into the project (never contain secrets). */
export async function writeDevDocs(dir: string, config: AgentConfig, template: Template): Promise<string[]> {
  const claudeMd = path.join(dir, 'CLAUDE.md');
  const brief = path.join(dir, 'DEVELOPMENT_BRIEF.md');
  await fs.writeFile(claudeMd, generateClaudeMd(config, template), 'utf8');
  await fs.writeFile(brief, generateDevBrief(config, template), 'utf8');
  return [claudeMd, brief];
}

async function gitAvailable(): Promise<boolean> {
  try {
    await execFileAsync('git', ['--version'], { timeout: 5000 });
    return true;
  } catch {
    return false;
  }
}

async function isGitRepo(dir: string): Promise<boolean> {
  return fs
    .access(path.join(dir, '.git'))
    .then(() => true)
    .catch(() => false);
}

export interface GitInitResult {
  gitAvailable: boolean;
  initialized: boolean;
  branch?: string;
  alreadyRepo: boolean;
}

/**
 * Initialize a git repo (if git is available and the dir isn't already one), make an initial
 * commit, and create a development branch. Best-effort — returns what happened.
 */
export async function initGitAndBranch(dir: string, branch = 'customize'): Promise<GitInitResult> {
  if (!(await gitAvailable())) return { gitAvailable: false, initialized: false, alreadyRepo: false };
  const already = await isGitRepo(dir);
  const run = (args: string[]) => execFileAsync('git', args, { cwd: dir, timeout: 15000 });

  if (!already) {
    await run(['init', '-q']);
    await run(['add', '-A']);
    // Commit may fail if user.name/email unset; set a local identity as a fallback.
    try {
      await run(['commit', '-q', '-m', 'Initial scaffold from create-zoom-agent']);
    } catch {
      await run(['config', 'user.email', 'dev@example.com']).catch(() => {});
      await run(['config', 'user.name', 'Zoom CLI']).catch(() => {});
      await run(['commit', '-q', '-m', 'Initial scaffold from create-zoom-agent']).catch(() => {});
    }
  }
  let createdBranch: string | undefined;
  try {
    await run(['checkout', '-q', '-b', branch]);
    createdBranch = branch;
  } catch {
    /* branch may already exist; ignore */
  }
  return { gitAvailable: true, initialized: !already, branch: createdBranch, alreadyRepo: already };
}

/** Launch an interactive Claude Code session in the project directory (inherits the user's auth). */
export function launchClaudeCode(dir: string): Promise<number> {
  return new Promise((resolve) => {
    const child = spawn('claude', [], { cwd: dir, stdio: 'inherit' });
    child.on('error', () => resolve(1));
    child.on('close', (code) => resolve(code ?? 0));
  });
}
